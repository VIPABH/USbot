@ABH.on(events.NewMessage(pattern=r'^\.الاوامر$', outgoing=True))
async def commands(e):
    text = "📋 **قائمة أقسام الأوامر:**\n\n"
    text += "\n".join(f"`{category}`" for category in info.keys())
    text += "\n\n💡 أرسل اسم القسم لعرض الأوامر الموجودة داخله."
    await e.edit(text)
@ABH.on(events.NewMessage(outgoing=True))
async def custom_commands(e):
    user_input = e.text.strip()
    if user_input in info:
        cmds_list = info[user_input]
        text = f"📂 **أوامر قسم `{user_input}`:**\n\n"
        for cmd, desc in cmds_list:
            text += f"• `{cmd}` : {desc}\n"
        await e.edit(text)
        return
    for category, cmds_list in info.items():
        for cmd, desc in cmds_list:
            if user_input == cmd:
                await e.edit(f"الامر: `{cmd}`\nالشرح: {desc}")
                return
